class Driver {
  final String name;
  final String nim;
  final String vehicle;
  final String plateNumber;
  final double rating;
  final double distance;
  final int price;
  final bool isOnline;

  const Driver({
    required this.name,
    required this.nim,
    required this.vehicle,
    required this.plateNumber,
    required this.rating,
    required this.distance,
    required this.price,
    required this.isOnline,
  });
}